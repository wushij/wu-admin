-- =============================================================================
-- add3.sql  增量补丁 #3（可重复执行）
-- =============================================================================
-- 菜单「即时聊天」更名为「企业IM」
-- 用法: mysql -u root -p wu-admin < sql/add3.sql
-- =============================================================================

USE `wu-admin`;

UPDATE sys_menu
SET name = '企业IM'
WHERE id = 172
  AND name IN ('即时聊天', '企业IM');

SELECT '[OK] add3.sql finished' AS result;
